"""Grow server/holt_server/seeds/repos.txt from free public lists, without GitHub search.

Sources (downloaded as plain files, no GitHub API):
  - GSoC 2026 organisations: summerofcode.withgoogle.com's public org API. An org
    whose source link is a repository is taken as is; an org link is mapped to its
    main contribution repos by hand (GSOC_ORG_REPOS below); CNCF is mapped to its
    graduated, incubating and sandbox projects from cncf/landscape's landscape.yml.
    Orgs not on GitHub
    (or only mirrored there) are skipped.
  - awesome-for-beginners (MunGell/awesome-for-beginners, README.md).
  - up-for-grabs (up-for-grabs/up-for-grabs.net, _data/projects/*.yml). Projects
    whose label stats were last updated before UFG_ACTIVE_SINCE are dropped.
  - goodfirstissue.dev (deepsourcelabs/good-first-issue, data/repositories.toml).
  - Hacktoberfest: `--hacktoberfest FILE`, one owner/repo per line (an export of
    repos Holt already knows that carry the `hacktoberfest` topic).

Everything above the GENERATED marker in repos.txt is kept verbatim; everything
below it is rebuilt. Catalogues (awesome-*, *-list, book lists, registries) and
contribution farms are dropped by name.

`--check` runs one batched GraphQL pass (100 repos per query, about 1 point per
query) and drops repos that are gone, archived, forks, or not pushed since
CHECK_ACTIVE_SINCE or under MIN_STARS stars, and writes renamed repos under their current name. It reads
GITHUB_TOKEN.

    GITHUB_TOKEN=$(gh auth token) uv run python scripts/build_seed_list.py --check \\
        [--hacktoberfest repos.txt] [--dry-run]
"""

