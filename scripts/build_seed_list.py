GH_REPO = re.compile(r"github\.com/([A-Za-z0-9-]+)/([A-Za-z0-9_.-]+)")


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "holt-seed-builder"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def repo_from(url: str) -> str | None:
    m = GH_REPO.search(url)
    if not m:
        return None
    owner, name = m.group(1), m.group(2).removesuffix(".git")
    if owner.lower() in {"orgs", "search", "topics", "sponsors", "apps", "marketplace"}:
        return None
    return f"{owner}/{name}"


def cncf() -> list[str]:
    import yaml  # installed with the server's dependencies

    out = []
    for cat in yaml.safe_load(get(CNCF_URL))["landscape"]:
        for sub in cat.get("subcategories") or []:
            for item in sub.get("items") or []:
                if item.get("project") in {"graduated", "incubating", "sandbox"}:
                    if r := repo_from(item.get("repo_url") or ""):
                        out.append(r)
    return out


def gsoc() -> list[str]:
    out: list[str] = []
    for org in json.loads(get(GSOC_URL)):
        url = org["source_code"].rstrip("/")
        if "github.com" not in url:
            host = url.split("/")[2] if "//" in url else url
            out += GSOC_OFF_GITHUB.get(host, [])
            continue
        path = url.split("github.com/", 1)[1].split("#")[0].split("?")[0]
        parts = [p for p in path.split("/") if p]
        key = "/".join(parts[:2]).lower() if len(parts) >= 2 else parts[0]
        umbrella = {k.lower(): v for k, v in GSOC_ORG_REPOS.items()}
        if key == "cncf":
            out += cncf()
        elif key in umbrella:
            out += umbrella[key]
        elif len(parts) == 1 or parts[0] == "search":
            out += umbrella.get(parts[0].lower(), [])
        elif parts[1] not in {".github", "ProjectIdeas", "GSoC", "gsoc"}:
            out.append(f"{parts[0]}/{parts[1]}")
    return out


def afb() -> list[str]:
    text = get(AFB_URL).decode("utf-8")
    return [r for u in re.findall(r"\]\((https://github\.com/[^)\s]+)\)", text)
            if (r := repo_from(u))]


def ufg() -> list[str]:
    out = []
    with tarfile.open(fileobj=io.BytesIO(get(UFG_URL)), mode="r:gz") as tar:
        for member in tar:
            if "/_data/projects/" not in member.name or not member.name.endswith(".yml"):
                continue
            text = tar.extractfile(member).read().decode("utf-8", "replace")
            site = re.search(r"^site:\s*(\S+)", text, re.M)
            updated = re.search(r"last-updated:\s*'?\"?(\d{4}-\d{2}-\d{2})", text)
            if not site or not updated or updated.group(1) < UFG_ACTIVE_SINCE:
                continue
            if r := repo_from(site.group(1)):
                out.append(r)
    return out


def gfi() -> list[str]:
    data = tomllib.loads(get(GFI_URL).decode("utf-8"))
    return [r for u in data["repositories"] if (r := repo_from(u))]


def skipped(repo: str) -> bool:
    return repo.lower() in SKIP_REPOS or bool(SKIP_NAME.search(repo.split("/")[1]))


def check(repos: list[str], token: str) -> tuple[dict[str, str | None], int]:
    """repo -> current nameWithOwner, or None when gone/archived/fork/dead.
    Returns the map and the GraphQL points it cost."""
    result: dict[str, str | None] = {}
    cost = 0
    for i in range(0, len(repos), 100):
        chunk = repos[i:i + 100]
        fields = "nameWithOwner isArchived isFork pushedAt stargazerCount"
        body = " ".join(
            f'r{j}: repository(owner: {json.dumps(r.split("/")[0])}, '
            f'name: {json.dumps(r.split("/")[1])}) {{ {fields} }}'
            for j, r in enumerate(chunk))
        query = f"query {{ rateLimit {{ cost }} {body} }}"
        req = urllib.request.Request(
            "https://api.github.com/graphql", data=json.dumps({"query": query}).encode(),
            headers={"Authorization": f"bearer {token}", "User-Agent": "holt-seed-builder"})
        with urllib.request.urlopen(req, timeout=120) as resp:
            data = json.loads(resp.read())["data"]
        cost += data["rateLimit"]["cost"]
        for j, r in enumerate(chunk):
            node = data.get(f"r{j}")
            ok = (node and not node["isArchived"] and not node["isFork"]
                  and (node["pushedAt"] or "") >= CHECK_ACTIVE_SINCE
                  and node["stargazerCount"] >= MIN_STARS)
            result[r] = node["nameWithOwner"] if ok else None
    return result, cost


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--hacktoberfest", help="file of owner/repo with the hacktoberfest topic")
    ap.add_argument("--check", action="store_true", help="one batched GraphQL liveness pass")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    text = SEEDS.read_text(encoding="utf-8")
    head = text.split(MARKER, 1)[0].rstrip("\n")
    seen = {line.split("#", 1)[0].strip().lower() for line in head.splitlines()} - {""}
    kept = len(seen)

    sources: list[tuple[str, str, list[str]]] = []
    if args.hacktoberfest:
        lines = Path(args.hacktoberfest).read_text(encoding="utf-8").splitlines()
        sources.append(("hacktoberfest", "repos Holt has seen with the hacktoberfest topic",
                        [r for line in lines if (r := repo_from("github.com/" + line.strip()))]))
    sources += [
        ("gsoc-2026", f"GSoC 2026 organisations ({GSOC_URL}), orgs mapped by hand", gsoc()),
        ("goodfirstissue.dev", GFI_URL, gfi()),
        ("awesome-for-beginners", AFB_URL, afb()),
        ("up-for-grabs", f"{UFG_URL} (label stats updated since {UFG_ACTIVE_SINCE})", ufg()),
    ]

    dropped: Counter[str] = Counter()
    blocks: list[tuple[str, str, list[str]]] = []
    for name, where, found in sources:
        new = []
        for repo in found:
            if repo.lower() in seen:
                dropped["duplicate"] += 1
            elif skipped(repo):
                dropped["catalogue or farm"] += 1
                seen.add(repo.lower())
            else:
                seen.add(repo.lower())
                new.append(repo)
        blocks.append((name, where, new))

    if args.check:
        token = os.environ.get("GITHUB_TOKEN")
        if not token:
            sys.exit("--check needs GITHUB_TOKEN")
        status, cost = check([r for _, _, b in blocks for r in b], token)
        print(f"GraphQL check cost {cost} points", file=sys.stderr)
        seen = {line.split("#", 1)[0].strip().lower() for line in head.splitlines()} - {""}
        checked = []
        for name, where, new in blocks:
            live = []
            for repo in new:
                current = status.get(repo)
                if current is None:
                    dropped[f"gone, archived, fork, under {MIN_STARS} stars or no push since {CHECK_ACTIVE_SINCE}"] += 1
                elif current.lower() in seen:
                    dropped["duplicate after rename"] += 1
                else:
                    seen.add(current.lower())
                    live.append(current)
            checked.append((name, where, live))
        blocks = checked

    out = [head, "", MARKER]
    for name, where, new in blocks:
        out += ["", f"# source: {name} ({len(new)}) {where}"] + sorted(new, key=str.lower)
    total = kept + sum(len(b) for _, _, b in blocks)
    for name, _, new in blocks:
        print(f"{name}: {len(new)} new", file=sys.stderr)
    for why, n in dropped.most_common():
        print(f"dropped ({why}): {n}", file=sys.stderr)
    print(f"kept {kept} existing; total {total}", file=sys.stderr)
    if not args.dry_run:
        SEEDS.write_text("\n".join(out) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
